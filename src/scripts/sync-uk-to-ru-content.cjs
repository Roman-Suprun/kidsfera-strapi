async function findSingle(strapi, uid, locale, populate = '*') {
  return normalizeSingle(
    await strapi.documents(uid).findMany({
      locale,
      status: PUBLISHED_STATUS,
      populate,
    }),
  );
}

async function findMany(strapi, uid, locale, sort = ['updatedAt:desc'], populate = '*') {
  const entries = await strapi.documents(uid).findMany({
    locale,
    status: PUBLISHED_STATUS,
    populate,
    sort,
    pagination: {
      page: 1,
      pageSize: 200,
    },
  });

  return Array.isArray(entries) ? entries : [];
}

async function updateLocalizedDocument(strapi, uid, ukEntry, locale, data) {
  return strapi.documents(uid).update({
    documentId: ukEntry.documentId,
    locale,
    status: PUBLISHED_STATUS,
    data,
  });
}

