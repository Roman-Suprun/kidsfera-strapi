function isRecord(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isMediaRecord(value) {
  return (
    isRecord(value) &&
    (typeof value.mime === 'string' ||
      typeof value.provider === 'string' ||
      ('formats' in value && typeof value.url === 'string'))
  );
}

function sanitizeDocumentInput(value, asRelation = true) {
  if (Array.isArray(value)) {
    return value.map((item) => sanitizeDocumentInput(item));
  }

  if (!isRecord(value)) {
    return value;
  }

  if (isMediaRecord(value)) {
    return typeof value.id === 'number' ? value.id : undefined;
  }

  if (asRelation && typeof value.documentId === 'string') {
    return { documentId: value.documentId };
  }

  return Object.fromEntries(
    Object.entries(value)
      .filter(
        ([key]) =>
          ![
            'id',
            'documentId',
            'createdAt',
            'updatedAt',
            'publishedAt',
            'locale',
            'localizations',
            'createdBy',
            'updatedBy',
          ].includes(key),
      )
      .map(([key, nestedValue]) => [key, sanitizeDocumentInput(nestedValue)])
      .filter(([, nestedValue]) => nestedValue !== undefined),
  );
}

function buildDocumentData(value) {
  return sanitizeDocumentInput(value, false);
}

function getMediaId(value) {
  return isRecord(value) && typeof value.id === 'number' ? value.id : undefined;
}

function mergePreservingRussianText(ukValue, ruValue) {
  if (Array.isArray(ukValue)) {
    const ruArray = Array.isArray(ruValue) ? ruValue : [];
    return ukValue.map((item, index) => mergePreservingRussianText(item, ruArray[index]));
  }

  if (!isRecord(ukValue)) {
    if (typeof ukValue === 'string') {
      return typeof ruValue === 'string' && ruValue.trim().length > 0 ? ruValue : ukValue;
    }

    return ukValue;
  }

  if (isMediaRecord(ukValue)) {
    return ukValue;
  }

  if (typeof ukValue.documentId === 'string') {
    return ukValue;
  }

  const result = {};

  for (const [key, value] of Object.entries(ukValue)) {
    result[key] = mergePreservingRussianText(value, isRecord(ruValue) ? ruValue[key] : undefined);
  }

  return result;
}

function normalizeSingle(result) {
  if (Array.isArray(result)) {
    return result[0] ?? null;
  }

  return result ?? null;
}

function mergeSeo(currentSeo, overrides) {
  return {
    metaTitle: currentSeo?.metaTitle ?? null,
    metaDescription: currentSeo?.metaDescription ?? null,
    ogTitle: currentSeo?.ogTitle ?? null,
    ogDescription: currentSeo?.ogDescription ?? null,
    canonicalPath: currentSeo?.canonicalPath ?? null,
    ogImage: currentSeo?.ogImage ?? null,
    ogImageUrl: currentSeo?.ogImageUrl ?? null,
    noIndex: currentSeo?.noIndex ?? false,
    ...overrides,
  };
}

function translateSimpleValue(value) {
  if (typeof value !== 'string') {
    return value;
  }

  return value
    .replace(/дітей/g, 'детей')
    .replace(/скелелазів/g, 'скалолазов')
    .replace(/осіб/g, 'человек')
    .replace(/тижнів/g, 'недель')
    .replace(/днів/g, 'дней')
    .replace(/смерека/g, 'ель')
    .replace(/Смерека/g, 'Ель')
    .replace(/Імпрегнована/g, 'Импрегнированная')
    .replace(/імпрегнована/g, 'импрегнированная')
    .replace(/Оцинкований дріт/g, 'Оцинкованный трос')
    .replace(/Оцинкована сталь/g, 'Оцинкованная сталь')
    .replace(/склопластик/g, 'стеклопластик')
    .replace(/кульки/g, 'шарики')
    .replace(/піна/g, 'пена')
    .replace(/зачепи/g, 'зацепы');
}

