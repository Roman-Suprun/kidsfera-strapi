function buildSeo(currentSeo, nextSeo) {
  return {
    metaTitle: currentSeo?.metaTitle ?? null,
    metaDescription: currentSeo?.metaDescription ?? null,
    ogTitle: currentSeo?.ogTitle ?? null,
    ogDescription: currentSeo?.ogDescription ?? null,
    canonicalPath: currentSeo?.canonicalPath ?? null,
    noIndex: currentSeo?.noIndex ?? false,
    ...nextSeo,
  };
}

async function main() {
  const printOnly = process.argv.includes('--print');
  const appContext = await compileStrapi();
  const strapi = await createStrapi(appContext).load();

  try {
    const posts = await strapi.documents(BLOG_POST_UID).findMany({
      locale: 'uk',
      status: PUBLISHED_STATUS,
      populate: {
        bodySections: true,
        seo: true,
      },
      sort: ['publishDate:desc'],
    });

    const targets = posts.filter((post) => translationsBySlug[post.slug]);

    if (printOnly) {
      console.log(
        JSON.stringify(
          targets.map((post) => ({
            documentId: post.documentId,
            slug: post.slug,
            currentTitle: post.title,
            nextTitle: translationsBySlug[post.slug].title,
          })),
          null,
          2,
        ),
      );
      return;
    }

    const results = [];

    for (const post of targets) {
      const translation = translationsBySlug[post.slug];
      const updated = await strapi.documents(BLOG_POST_UID).update({
        documentId: post.documentId,
        locale: 'uk',
        status: PUBLISHED_STATUS,
        data: {
          title: translation.title,
          excerpt: translation.excerpt,
          authorRole: translation.authorRole,
          bodySections: translation.bodySections,
          seo: buildSeo(post.seo, translation.seo),
        },
      });

      results.push({
        documentId: updated.documentId,
        slug: updated.slug,
        locale: updated.locale,
        title: updated.title,
        updatedAt: updated.updatedAt,
      });
    }

    console.log(JSON.stringify({ updated: results }, null, 2));
  } finally {
    try {
      await strapi.destroy();
    } catch (error) {
      if (!String(error).includes('aborted')) {
        throw error;
      }
    }
  }
}

main()
  .then(() => {
    process.exitCode = 0;
  })
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
